    "# [04] 텍스트 피처 추출 (7개 — 04 Baseline과 동일)\n"
    "MENU_WORDS = {\n"
    "    'chicken','beef','pizza','salad','pasta','fish','shrimp','steak',\n"
    "    'burger','sandwich','soup','rice','noodles','sushi','tacos','bread',\n"
